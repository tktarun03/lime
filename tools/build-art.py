import os, json, sys
from PIL import Image
SRC, DST, JS = sys.argv[1], sys.argv[2], sys.argv[3]
THUMB_POSE = {'jump-squat': 'a', 'deadlift': 'a', 'neg-pullup': 'a'}
ids = sorted({f.rsplit('-', 1)[0] for f in os.listdir(SRC) if f.endswith('.png')})
art = {}
total = 0
for i in ids:
    a = Image.open(f'{SRC}/{i}-a.png').convert('RGBA')
    b = Image.open(f'{SRC}/{i}-b.png').convert('RGBA')
    assert a.size == b.size, i
    def bb(im):
        al = im.getchannel('A').point(lambda v: 255 if v > 24 else 0)
        return al.getbbox()
    ba, bbx = bb(a), bb(b)
    x0, y0 = min(ba[0], bbx[0]), min(ba[1], bbx[1])
    x1, y1 = max(ba[2], bbx[2]), max(ba[3], bbx[3])
    pad = max(16, int(0.04 * max(x1 - x0, y1 - y0)))
    box = (max(0, x0 - pad), max(0, y0 - pad), min(a.width, x1 + pad), min(a.height, y1 + pad))
    ca, cb = a.crop(box), b.crop(box)
    scale = min(1, 760 / max(ca.size))
    size = (round(ca.width * scale), round(ca.height * scale))
    ca, cb = ca.resize(size, Image.LANCZOS), cb.resize(size, Image.LANCZOS)
    for s, im in (('a', ca), ('b', cb)):
        p = f'{DST}/{i}-{s}.webp'
        im.save(p, 'WEBP', quality=80, method=6, alpha_quality=90)
        total += os.path.getsize(p)
    t = (ca if THUMB_POSE.get(i) == 'a' else cb).copy()
    t = t.crop(t.getchannel('A').getbbox())
    t.thumbnail((152, 152), Image.LANCZOS)
    sq = Image.new('RGBA', (160, 160), (0, 0, 0, 0))
    sq.alpha_composite(t, ((160 - t.width) // 2, 160 - 4 - t.height if t.height < 150 else (160 - t.height) // 2))
    p = f'{DST}/{i}-t.webp'; sq.save(p, 'WEBP', quality=80, method=6); total += os.path.getsize(p)
    art[i] = [size[0], size[1]]
lines = ',\n'.join(f"    '{k}': [{v[0]}, {v[1]}]" for k, v in art.items())
open(JS, 'w').write(f"""/* Exercise photos (generated by tools/build-art.py — do not edit by hand).
   Each id has media/ex/<id>-a.webp (start), -b.webp (end) and -t.webp
   (thumbnail). a and b share one crop so they line up when blended.
   Value = [width, height] of a/b in pixels. */
(function () {{
  'use strict';
  LIME.ART = {{
{lines}
  }};
}})();
""")
print(len(art), 'exercises,', round(total / 1024), 'KB total')
