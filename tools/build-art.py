#!/usr/bin/env python3
"""Turn exercise PNGs into the app's photo files.

Usage:
  python3 tools/build-art.py <png-folder>              # woman (default)  -> media/ex/
  python3 tools/build-art.py <png-folder> --athlete m  # man              -> media/ex/m/

The folder holds <exercise-id>-a.png (start) and <exercise-id>-b.png (end),
1200x1200 with a transparent background. Only the ids in the folder are
(re)built; other photos are left alone. Then js/data/art.js is regenerated
from every photo on disk, so it always matches the files.

Per pair: faint background haze (alpha < 24) and specks under 200 px are
removed, both images get one shared crop (so they line up when blended),
are scaled to at most 760 px and saved as WebP, plus a 160 px thumbnail.
Needs Pillow (with WebP) and SciPy.
"""
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THUMB_POSE = {'jump-squat': 'a', 'deadlift': 'a', 'neg-pullup': 'a'}
ATHLETES = {'w': ('media/ex', 'ART'), 'm': ('media/ex/m', 'ART_M')}


def clean(im):
    a = np.array(im.convert('RGBA'))
    al = a[:, :, 3]
    al[al < 24] = 0
    lab, n = ndimage.label(al > 0)
    if n > 1:
        sizes = ndimage.sum(al > 0, lab, range(1, n + 1))
        for i, s in enumerate(sizes, 1):
            if s < 200:
                al[lab == i] = 0
    a[:, :, 3] = al
    return Image.fromarray(a)


def build(src, athlete):
    rel, _ = ATHLETES[athlete]
    dst = os.path.join(ROOT, rel)
    os.makedirs(dst, exist_ok=True)
    ids = sorted({f.rsplit('-', 1)[0] for f in os.listdir(src) if f.endswith('-a.png')})
    done = 0
    for i in ids:
        pb = os.path.join(src, f'{i}-b.png')
        if not os.path.exists(pb):
            print(f'skip {i}: no {i}-b.png'); continue
        a = clean(Image.open(os.path.join(src, f'{i}-a.png')))
        b = clean(Image.open(pb))
        if a.size != b.size:
            print(f'skip {i}: start and end are different sizes'); continue
        ba, bbx = a.getchannel('A').getbbox(), b.getchannel('A').getbbox()
        x0, y0 = min(ba[0], bbx[0]), min(ba[1], bbx[1])
        x1, y1 = max(ba[2], bbx[2]), max(ba[3], bbx[3])
        pad = max(16, int(0.04 * max(x1 - x0, y1 - y0)))
        box = (max(0, x0 - pad), max(0, y0 - pad), min(a.width, x1 + pad), min(a.height, y1 + pad))
        ca, cb = a.crop(box), b.crop(box)
        scale = min(1, 760 / max(ca.size))
        size = (round(ca.width * scale), round(ca.height * scale))
        ca, cb = ca.resize(size, Image.LANCZOS), cb.resize(size, Image.LANCZOS)
        ca.save(f'{dst}/{i}-a.webp', 'WEBP', quality=80, method=6, alpha_quality=90)
        cb.save(f'{dst}/{i}-b.webp', 'WEBP', quality=80, method=6, alpha_quality=90)
        t = (ca if THUMB_POSE.get(i) == 'a' else cb).copy()
        t = t.crop(t.getchannel('A').getbbox())
        t.thumbnail((152, 152), Image.LANCZOS)
        sq = Image.new('RGBA', (160, 160), (0, 0, 0, 0))
        sq.alpha_composite(t, ((160 - t.width) // 2, 160 - 4 - t.height if t.height < 150 else (160 - t.height) // 2))
        sq.save(f'{dst}/{i}-t.webp', 'WEBP', quality=80, method=6)
        done += 1
    print(f'{done} exercise(s) built for athlete {athlete} in {rel}/')


def write_js():
    blocks = []
    for athlete, (rel, var) in ATHLETES.items():
        d = os.path.join(ROOT, rel)
        art = {}
        if os.path.isdir(d):
            for f in sorted(os.listdir(d)):
                if f.endswith('-a.webp'):
                    i = f[:-len('-a.webp')]
                    if all(os.path.exists(os.path.join(d, f'{i}-{s}.webp')) for s in 'bt'):
                        w, h = Image.open(os.path.join(d, f)).size
                        art[i] = [w, h]
        lines = ',\n'.join(f"    '{k}': [{v[0]}, {v[1]}]" for k, v in art.items())
        blocks.append(f"  // {'woman' if athlete == 'w' else 'man'}: {rel}/ ({len(art)} exercises)\n  LIME.{var} = {{\n{lines}\n  }};")
    js = """/* Exercise photos (generated by tools/build-art.py — do not edit by hand).
   Each id has <dir>/<id>-a.webp (start), -b.webp (end) and -t.webp
   (thumbnail). a and b share one crop so they line up when blended.
   Value = [width, height] of a/b in pixels. ART = woman, ART_M = man;
   a missing man photo falls back to the woman's. */
(function () {
  'use strict';
""" + '\n'.join(blocks) + "\n})();\n"
    open(os.path.join(ROOT, 'js/data/art.js'), 'w').write(js)
    print('js/data/art.js updated')


if __name__ == '__main__':
    args = sys.argv[1:]
    athlete = 'w'
    if '--athlete' in args:
        k = args.index('--athlete'); athlete = args[k + 1]; del args[k:k + 2]
    if athlete not in ATHLETES or len(args) != 1:
        sys.exit(__doc__)
    build(args[0], athlete)
    write_js()
